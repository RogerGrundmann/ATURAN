// u_ref(lat) for the model whose planet_tag() is <tag>, linear in latitude between the 1-deg rows; 0 for an unknown tag.
inline double u(const char* tag, double lat_deg){
    const double* t = !strcmp(tag, "ATJUP") ? u_atjup : !strcmp(tag, "ATSAT") ? u_atsat
                    : !strcmp(tag, "ATURAN") ? u_aturan : !strcmp(tag, "ATNEPT") ? u_atnept : nullptr;
    if(!t) return 0.0;
    double x = lat_deg + 90.0;
    if(x <= 0.0) return t[0];
    if(x >= 180.0) return t[180];
    const int i0 = (int)std::floor(x);
    const double f = x - i0;
    return (1.0 - f) * t[i0] + f * t[i0 + 1];
}

template<class Planet> inline bool on(){
    static const int v = ATPhys::env_int(Planet::planet_tag(), "JET_REF", 0);
    return v != 0;
}

template<class Planet> inline double u_ref(double lat_deg){ return u(Planet::planet_tag(), lat_deg); }

